-- Never rely on Supabase default grants; grant only what is listed below.
revoke all on all tables in schema public from anon, authenticated;
revoke all on all functions in schema public from anon, authenticated;
-- PUBLIC's execute default is global; IN SCHEMA can't revoke it
alter default privileges for role postgres revoke execute on functions from public;
alter default privileges for role postgres in schema public revoke execute on functions from anon, authenticated;
-- Supabase also default-grants new tables and sequences to anon/authenticated
alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated;
alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated;

create table public.event (
  id int primary key check (id = 1),
  name text not null,
  status text not null default 'setup' check (status in ('setup', 'voting', 'revealed')),
  reveal_at timestamptz,
  entries_open boolean not null default true
);
