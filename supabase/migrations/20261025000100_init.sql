create function public.get_event()
returns table (name text, status text, reveal_at timestamptz, entries_open boolean, server_now timestamptz)
language sql stable security definer set search_path = ''
as $$
  select e.name, e.status, e.reveal_at, e.entries_open, now()
  from public.event e where e.id = 1;
$$;

create function public.voting_open()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select coalesce(e.status = 'voting' and e.reveal_at is not null and now() < e.reveal_at, false)
  from public.event e where e.id = 1;
$$;

create function public.get_chilis()
returns table (id uuid, pot_number int, name text, description text, cook text, allergen_ids text[])
language sql stable security definer set search_path = ''
as $$
  select c.id, c.pot_number, c.name, c.description,
    case when e.reveal_at <= now() then c.cook end,
    coalesce(array(
      select ca.allergen_id from public.chili_allergens ca
      where ca.chili_id = c.id order by ca.allergen_id), '{}')
  from public.chilis c cross join public.event e
  where e.id = 1
  order by c.pot_number;
$$;

create function public.get_tag_counts()
returns table (chili_id uuid, tag_id text, count int)
language sql stable security definer set search_path = ''
as $$
  select ct.chili_id, ct.tag_id, count(*)::int
  from public.chili_tags ct group by ct.chili_id, ct.tag_id;
$$;

create function public.get_results()
returns table (chili_id uuid, pot_number int, name text, cook text, points int,
  firsts int, seconds int, thirds int, rank int)
language sql stable security definer set search_path = ''
as $$
  with t as (
    select c.id, c.pot_number, c.name, c.cook,
      (select count(*)::int from public.ballots b where b.first_id = c.id) as f,
      (select count(*)::int from public.ballots b where b.second_id = c.id) as s,
      (select count(*)::int from public.ballots b where b.third_id = c.id) as th
    from public.chilis c
    where exists (select 1 from public.event e
      where e.id = 1 and e.reveal_at is not null and now() >= e.reveal_at)
  )
  select t.id, t.pot_number, t.name, t.cook,
    t.f * 3 + t.s * 2 + t.th, t.f, t.s, t.th,
    (rank() over (order by (t.f * 3 + t.s * 2 + t.th) desc, t.f desc, t.s desc))::int
  from t
  order by 9, t.pot_number;
$$;

create function public.ballot_count()
returns int
language sql stable security definer set search_path = ''
as $$
  select count(*)::int from public.ballots;
$$;

grant execute on function
  public.get_event(), public.voting_open(), public.get_chilis(),
  public.get_tag_counts(), public.get_results(), public.ballot_count()
  to anon, authenticated;
