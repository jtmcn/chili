create table public.chilis (
  id uuid primary key default gen_random_uuid(),
  pot_number int generated by default as identity unique,
  name text not null,
  description text,
  cook text,
  owner_device_id text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index chilis_name_ci on public.chilis (lower(name));

create table public.allergens (
  id text primary key,
  label text not null,
  same_as text,
  sort int not null
);
create table public.tags (
  id text primary key,
  label text not null,
  same_as text,
  sort int not null
);

create table public.chili_allergens (
  chili_id uuid not null references public.chilis on delete cascade,
  allergen_id text not null references public.allergens,
  primary key (chili_id, allergen_id)
);
create table public.chili_tags (
  chili_id uuid not null references public.chilis on delete cascade,
  tag_id text not null references public.tags,
  device_id text not null,
  created_at timestamptz not null default now(),
  primary key (chili_id, tag_id, device_id)
);
create table public.ballots (
  device_id text primary key,
  first_id uuid references public.chilis on delete set null,
  second_id uuid references public.chilis on delete set null,
  third_id uuid references public.chilis on delete set null,
  updated_at timestamptz not null default now(),
  constraint ballots_distinct check (
    first_id <> second_id and first_id <> third_id and second_id <> third_id
  )
);

